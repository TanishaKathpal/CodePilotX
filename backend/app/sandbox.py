"""Running tests in an isolated Docker container.

Repository code is UNTRUSTED. It is never imported or executed in the API process. The only way
this project runs repository code is `docker run` with these restrictions:

  --network none                no internet, no access to your LAN or cloud metadata endpoints
  --memory / --memory-swap      hard RAM cap (OOM-killed if exceeded)
  --cpus, --pids-limit          CPU cap and protection against fork bombs
  --cap-drop ALL, no-new-privileges, non-root user (65534)
  --read-only root filesystem   only /work (a throw-away COPY of the repo), /out and a small
                                /tmp are writable
  --ulimit fsize/nofile         cap on file sizes and open files
  wall-clock timeout            container is killed (`docker kill`) when it expires

If Docker (or the sandbox image) is unavailable we do NOT fall back to running on the host. The
result is simply "could not run", and the app reports the fix as NOT validated.

Remaining risk, stated honestly: a container is strong isolation but not a perfect security
boundary (kernel/runtime bugs exist). For hostile multi-tenant use, add gVisor/Firecracker.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
import time
import uuid
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Protocol

from .config import Settings
from .models import TestOutcome, TestRunResult

MAX_XML_BYTES = 5 * 1024 * 1024
OUTPUT_TAIL_CHARS = 4000


class Sandbox(Protocol):
    def availability(self) -> tuple[bool, str]: ...
    def run_tests(self, workdir: Path, targets: list[str]) -> TestRunResult: ...


_WIN_DRIVE = re.compile(r"^[A-Za-z]:[\\/]")


def _bind_mount(host_path: Path, container_path: str) -> str:
    """Build the value for `docker run -v`, e.g. '/srv/job:/work:rw' (Linux/macOS) or
    'C:\\Users\\me\\job:/work:rw' (Windows - Docker Desktop accepts native Windows paths).

    The host path is written with the platform's own separators on purpose: that is the form
    Docker expects on each platform. What we must guard against is a path that CHANGES THE
    MEANING of the spec. In `-v host:container:mode` a colon is the separator, so a host path
    containing one (other than a Windows drive letter like 'C:') would let the spec be
    reinterpreted. Newlines are rejected too. Our paths are normally generated by us, but
    WORKSPACE_DIR is user-configurable, so we validate instead of assuming.
    """
    text = str(host_path)
    if not os.path.isabs(text):
        raise ValueError(f"Sandbox mount path must be absolute: {text!r}")
    rest = text[2:] if _WIN_DRIVE.match(text) else text
    if ":" in rest or "\n" in text or "\r" in text or "\0" in text:
        raise ValueError(f"Unsafe character in sandbox mount path: {text!r} (':' and line breaks are not allowed)")
    return f"{text}:{container_path}:rw"


def build_docker_command(settings: Settings, workdir: Path, outdir: Path, container_name: str,
                         targets: list[str]) -> list[str]:
    """Pure function (easy to unit-test): the exact `docker run` command line."""
    return [
        "docker", "run", "--rm", "--name", container_name,
        "--network", "none",
        "--memory", settings.sandbox_memory, "--memory-swap", settings.sandbox_memory,
        "--cpus", settings.sandbox_cpus,
        "--pids-limit", str(settings.sandbox_pids),
        "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
        "--read-only", "--tmpfs", "/tmp:rw,size=64m,noexec,nosuid",
        "--ulimit", "nofile=256:256", "--ulimit", "fsize=52428800",
        "--user", "65534:65534",
        "-e", "PYTHONPATH=/work:/work/src", "-e", "PYTHONDONTWRITEBYTECODE=1", "-e", "HOME=/tmp",
        "-v", _bind_mount(workdir, "/work"), "-v", _bind_mount(outdir, "/out"),
        "-w", "/work",
        settings.sandbox_image,
        "python", "-m", "pytest", "-q", "-p", "no:cacheprovider", "--tb=short",
        "--junitxml=/out/junit.xml",
        "--",  # everything after this is a path, never an option (paths come from untrusted repos)
        *targets,
    ]


def parse_junit(xml_text: str) -> list[TestOutcome]:
    """Parse pytest's junit XML. The XML comes from inside the sandbox, so it is treated as
    hostile: size-capped and DOCTYPE/ENTITY declarations (XML bombs) are rejected."""
    if len(xml_text) > MAX_XML_BYTES:
        raise ValueError("junit XML too large")
    low = xml_text[:4096].lower()
    if "<!doctype" in low or "<!entity" in low or "<!entity" in xml_text.lower():
        raise ValueError("junit XML contains a DOCTYPE/ENTITY declaration")
    root = ET.fromstring(xml_text)
    outcomes: list[TestOutcome] = []
    for tc in root.iter("testcase"):
        cls, name = tc.get("classname") or "", tc.get("name") or ""
        tid = f"{cls}::{name}" if cls else name
        status, msg = "passed", ""
        for tag, st in (("failure", "failed"), ("error", "error"), ("skipped", "skipped")):
            el = tc.find(tag)
            if el is not None:
                status = st
                msg = (el.get("message") or el.text or "")[:400]
                break
        outcomes.append(TestOutcome(id=tid, status=status, message=msg))
    return outcomes


def _make_world_writable(path: Path) -> None:
    """The container runs as an unprivileged user; our throw-away copy must be writable by it."""
    for dirpath, dirs, files in os.walk(path):
        os.chmod(dirpath, 0o777)
        for f in files:
            try:
                os.chmod(os.path.join(dirpath, f), 0o666)
            except OSError:
                pass


class DockerSandbox:
    def __init__(self, settings: Settings):
        self.settings = settings

    def availability(self) -> tuple[bool, str]:
        if shutil.which("docker") is None:
            return False, "Docker is not installed or not on PATH."
        try:
            info = subprocess.run(["docker", "info"], capture_output=True, text=True, timeout=15)
        except (subprocess.TimeoutExpired, OSError):
            return False, "Docker did not respond (is the Docker daemon running?)."
        if info.returncode != 0:
            return False, "Docker daemon is not reachable (is Docker Desktop / the service running?)."
        img = subprocess.run(["docker", "image", "inspect", self.settings.sandbox_image],
                             capture_output=True, text=True, timeout=15)
        if img.returncode != 0:
            return False, (f"Sandbox image '{self.settings.sandbox_image}' not found. "
                           "Build it with: docker build -t codepilotx-sandbox sandbox/")
        return True, "ok"

    def run_tests(self, workdir: Path, targets: list[str]) -> TestRunResult:
        ok, why = self.availability()
        if not ok:
            return TestRunResult(ran=False, error=why)
        s = self.settings
        name = f"codepilotx-{uuid.uuid4().hex[:12]}"
        outdir = Path(tempfile.mkdtemp(prefix="cpx-out-", dir=str(s.workspace_dir)))
        try:
            _make_world_writable(workdir)
            os.chmod(outdir, 0o777)
            try:
                cmd = build_docker_command(s, workdir.resolve(), outdir.resolve(), name, targets)
            except ValueError as e:  # unsafe/relative mount path (e.g. odd WORKSPACE_DIR)
                return TestRunResult(ran=False, error=f"Refusing to start the sandbox: {e}")
            t0 = time.time()
            try:
                proc = subprocess.run(cmd, capture_output=True, text=True,
                                      timeout=s.sandbox_timeout_s, errors="replace")
            except subprocess.TimeoutExpired:
                subprocess.run(["docker", "kill", name], capture_output=True, timeout=30)
                return TestRunResult(ran=False, duration_s=time.time() - t0,
                                     error=f"Tests exceeded the {s.sandbox_timeout_s}s time limit and were killed.")
            dur = time.time() - t0
            tail = ((proc.stdout or "") + (proc.stderr or ""))[-OUTPUT_TAIL_CHARS:]
            xml_path = outdir / "junit.xml"
            if proc.returncode in (125, 126, 127):
                return TestRunResult(ran=False, exit_code=proc.returncode, duration_s=dur, output_tail=tail,
                                     error="Docker could not start the test container.")
            if not xml_path.is_file():
                return TestRunResult(ran=False, exit_code=proc.returncode, duration_s=dur, output_tail=tail,
                                     error=("pytest produced no results (it may have crashed, run out of "
                                            "memory, or is not installed in the sandbox image)."))
            try:
                outcomes = parse_junit(xml_path.read_text(encoding="utf-8", errors="replace"))
            except (ET.ParseError, ValueError) as e:
                return TestRunResult(ran=False, exit_code=proc.returncode, duration_s=dur, output_tail=tail,
                                     error=f"Could not read test results ({type(e).__name__}).")
            return TestRunResult(ran=True, outcomes=outcomes, exit_code=proc.returncode,
                                 duration_s=dur, output_tail=tail)
        finally:
            shutil.rmtree(outdir, ignore_errors=True)
